import { mkdir, writeFile } from 'node:fs/promises';
import { createClientPlugin } from '../client/index.mjs';
// DSH serves lazy factory registrations; require('react') inside the factory
// resolves to the GUI's own React singleton.
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(new URL('../lib/client.js', import.meta.url), `// Generated by scripts/build.mjs; edit client/index.mjs instead.\nwindow.__ModuleLoader__.load({ id: 'dsh-desktop-ui', factory: (${createClientPlugin.toString()}) });\n`);
console.log('Built dsh-desktop-ui client.');
